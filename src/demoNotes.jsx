
// difference btw functional and class component

// functional component is a simple JavaScript function that returns JSX. 
// It does not have its own state or lifecycle methods. 
// It is also known as a stateless component.

// class component is a JavaScript class that extends React.
// Component. It has its own state and lifecycle methods. 
// It is also known as a stateful component.

// state less component is a component that does not have its own state. 
// It relies on props to receive data and render the UI. 
// // It is also known as a functional component.

// stateful component is a component that has its own state. 
// It can manage its own data and render the UI based on that data./


// DOM vs Virtual DOM
// DOM (Document Object Model) is a programming interface for HTML and XML documents.
// It represents the page so that programs can change the document structure, style, and content.

// Virtual DOM is a lightweight copy of the real DOM.
// It is a JavaScript object that represents the real DOM.
// When a component's state changes, React creates a new Virtual DOM tree and compares it with the previous one.
// If there are differences, React updates the real DOM to reflect those changes.
